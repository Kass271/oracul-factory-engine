#!/usr/bin/env node
// Generates docs/<phase>/05_release/qa/traceability.md: FR → spec → slice → tests → result → evidence.
// Built ONLY from real outputs: @trace tags, JUnit XML, Playwright JSON, verify's last-run.json, screenshots.
// Exit 1 if any delivered FR has no passing test (BLOCKED FRs are listed as BLOCKED, not hidden).
import fs from 'node:fs';
import path from 'node:path';
import { context, exists, lastRunPath, listPhases, parseArgs, readJson, readText, today } from './lib/core.mjs';
import { allRequirements, collectTraces, frsOf, parsePlan, parseSpecs } from './lib/docs.mjs';
import { junitCases } from './lib/red.mjs';

const args = parseArgs();
const ctx = context(args);
if (!ctx.phaseDir) { console.error('gen-traceability: no app/phase selected'); process.exit(1); }
const at = (p) => path.join(ctx.appDir, p);

// --- results per test file ---
const results = new Map(); // rel -> 'pass' | 'fail'
const set = (rel, ok) => { if (results.get(rel) !== 'fail') results.set(rel, ok ? 'pass' : 'fail'); };

// Per test case: a test passes when one of its attempts passed (a retry that passed = flaky, like Playwright's
// "flaky" status). A class with no executed test case does not count as passing.
const junitDir = at('backend/build/test-results/test');
for (const c of junitCases(junitDir).values()) set(c.file, c.attempts.some((a) => a.ok));
// Fail-safe: a suite whose header counts failures but whose cases show no failed attempt is inconsistent → fail.
if (exists(junitDir)) {
  for (const f of fs.readdirSync(junitDir).filter((x) => x.endsWith('.xml'))) {
    const xml = readText(path.join(junitDir, f)) || '';
    const m = xml.match(/<testsuite[^>]*name="([^"]+)"[^>]*tests="(\d+)"[^>]*failures="(\d+)"[^>]*errors="(\d+)"/);
    if (!m) continue;
    const rel = `backend/src/test/java/${m[1].replace(/\$.*$/, '').replace(/\./g, '/')}.java`;
    if (Number(m[2]) === 0) set(rel, false);
    else if ((m[3] !== '0' || m[4] !== '0') && !/<(failure|error)\b/.test(xml)) set(rel, false);
  }
}

const pw = readJson(at('e2e/report/results.json'));
// Playwright records rootDir as a real path; the app path may run through a symlink (macOS /var → /private/var).
const real = (p) => { try { return fs.realpathSync(p); } catch { return path.resolve(p); } };
const pwRoot = pw?.config?.rootDir ? path.relative(real(at('e2e')), real(pw.config.rootDir)).split(path.sep).join('/') : 'tests';
const walkSuites = (s) => {
  for (const spec of s.specs || []) {
    const ok = (spec.tests || []).every((t) => ['expected', 'flaky'].includes(t.status));
    set(`e2e/${path.posix.join(pwRoot, spec.file)}`, ok);
  }
  (s.suites || []).forEach(walkSuites);
};
if (pw) (pw.suites || []).forEach(walkSuites);

const lastRun = readJson(lastRunPath(ctx.app || 'fixture')) || readJson(args['last-run'] || '') || {};
const layerOk = (layer) => lastRun.layers?.[layer]?.exit === 0;

// --- documents ---
const reqs = frsOf(allRequirements(ctx.appDir));
const traces = collectTraces(ctx.appDir);
const specOf = {}, sliceOf = {};
for (const ph of listPhases(ctx.appDir)) {
  const dir = at(`docs/${ph}`);
  for (const s of parseSpecs(dir)) for (const id of s.covers) specOf[id] = `${ph}/02_specs/${s.file}`;
  for (const s of parsePlan(dir) || []) for (const id of s.frs) sliceOf[id] = { phase: ph, slice: s.slice };
}
const slices = ctx.state?.slices || {};
const shots = (ph) => { const d = at(`docs/${ph}/05_release/qa/screenshots`); return exists(d) ? fs.readdirSync(d) : []; };

let failed = 0, blocked = 0;
const rows = reqs.map((f) => {
  const sl = sliceOf[f.id];
  const isBlocked = sl && sl.phase === ctx.phase && slices[sl.slice] === 'BLOCKED';
  const tests = traces.get(f.id) || [];
  const verdicts = tests.map((t) => results.get(t.rel) ?? (t.layer !== 'e2e' && layerOk(t.layer) ? 'pass' : 'unknown'));
  const evidence = shots(f.phase).filter((s) => s.startsWith(`${f.id}-`)).map((s) => `[${s}](../../../${f.phase}/05_release/qa/screenshots/${s})`);
  let result;
  if (isBlocked) { result = 'BLOCKED'; blocked++; }
  else if (tests.length && verdicts.every((v) => v === 'pass')) result = '✔';
  else { result = '✘'; failed++; }
  const testCell = tests.map((t, i) => `\`${t.rel}\` (${verdicts[i]})`).join('<br>') || '—';
  return `| ${f.id} | ${f.phase} | ${f.title} | ${specOf[f.id] ?? '—'} | ${sl?.slice ?? '—'} | ${testCell} | ${result} | ${evidence.join(' ') || '—'} |`;
});

const out = [
  `# Traceability — ${ctx.app ?? path.basename(ctx.appDir)}`,
  '',
  `Generated by gen-traceability on ${today()} — do not edit by hand.`,
  '',
  `Delivered: ${reqs.length - failed - blocked} ✔ · Failed or untested: ${failed} ✘ · Blocked: ${blocked}`,
  '',
  '| FR | Phase | Title | Spec | Slice | Tests (result) | Result | Evidence |',
  '|---|---|---|---|---|---|---|---|',
  ...rows,
  '',
].join('\n');
const target = path.join(ctx.phaseDir, '05_release', 'qa', 'traceability.md');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`traceability.md written: ${reqs.length} FR, ${failed} ✘, ${blocked} blocked`);
process.exit(failed ? 1 : 0);
